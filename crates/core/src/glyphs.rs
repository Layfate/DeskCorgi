/// Strokes for a key symbol (by its label token), on the same grid.
fn symbol(token: &str) -> Option<Strokes> {
    let l = line;
    Some(match token {
        "SHIFT" => vec![l(&[(2.0, 0.0), (4.2, 3.0), (3.0, 3.0), (3.0, 6.0), (1.0, 6.0), (1.0, 3.0), (-0.2, 3.0), (2.0, 0.0)])],
        "CAPS" => vec![l(&[(2.0, 0.0), (4.2, 2.6), (3.0, 2.6), (3.0, 4.4), (1.0, 4.4), (1.0, 2.6), (-0.2, 2.6), (2.0, 0.0)]), l(&[(1.0, 6.0), (3.0, 6.0)])],
        "ENTER" => vec![l(&[(4.0, 0.0), (4.0, 4.0), (0.3, 4.0)]), l(&[(1.8, 2.5), (0.3, 4.0), (1.8, 5.5)])],
        "BKSP" | "LEFT" => vec![l(&[(4.0, 3.0), (0.2, 3.0)]), l(&[(1.8, 1.4), (0.2, 3.0), (1.8, 4.6)])],
        "RIGHT" => vec![l(&[(0.0, 3.0), (3.8, 3.0)]), l(&[(2.2, 1.4), (3.8, 3.0), (2.2, 4.6)])],
        "UP" => vec![l(&[(2.0, 6.0), (2.0, 0.4)]), l(&[(0.4, 2.0), (2.0, 0.4), (3.6, 2.0)])],
        "DOWN" => vec![l(&[(2.0, 0.0), (2.0, 5.6)]), l(&[(0.4, 4.0), (2.0, 5.6), (3.6, 4.0)])],
        "TAB" => vec![l(&[(0.0, 3.0), (3.4, 3.0)]), l(&[(1.8, 1.4), (3.4, 3.0), (1.8, 4.6)]), l(&[(4.2, 0.9), (4.2, 5.1)])],
        "WIN" => vec![
            l(&[(0.2, 0.8), (1.8, 0.8), (1.8, 2.6), (0.2, 2.6), (0.2, 0.8)]),
            l(&[(2.4, 0.8), (4.0, 0.8), (4.0, 2.6), (2.4, 2.6), (2.4, 0.8)]),
            l(&[(0.2, 3.4), (1.8, 3.4), (1.8, 5.2), (0.2, 5.2), (0.2, 3.4)]),
            l(&[(2.4, 3.4), (4.0, 3.4), (4.0, 5.2), (2.4, 5.2), (2.4, 3.4)]),
        ],
        _ => return None,
    })
}

/// Laid-out strokes for a key label token, with its width in grid units (height is
/// `GLYPH_H`). Symbol tokens (SHIFT, ENTER, arrows…) become one symbol; anything else
/// (letters, SPACE, CTRL, F5…) is spelled out letter by letter.
pub fn layout(token: &str) -> (Strokes, f32) {
    if let Some(s) = symbol(token) {
        return (s, GLYPH_W);
    }
    let mut out = Vec::new();
    let mut x = 0.0;
    let mut first = true;
    for c in token.chars() {
        if !first {
            x += ADVANCE - GLYPH_W;
        }
        first = false;
        if let Some(g) = glyph(c) {
            out.extend(g.into_iter().map(|st| st.into_iter().map(|q| q + pt(x, 0.0)).collect::<Vec<_>>()));
        }
        x += GLYPH_W;
    }
    (out, x.max(GLYPH_W))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::keymap::label_from_set1;

    #[test]
    fn space_is_spelled_out() {
        let (strokes, w) = layout("SPACE");
        assert!(strokes.len() >= 5, "one or more strokes per letter");
        assert!((w - (5.0 * GLYPH_W + 4.0 * (ADVANCE - GLYPH_W))).abs() < 1e-3);
    }

    #[test]
    fn every_key_label_can_be_drawn() {
        for make in 0..0x100u16 {
            for e0 in [false, true] {
                if let Some(label) = label_from_set1(make, e0) {
                    let (strokes, w) = layout(label);
                    assert!(!strokes.is_empty(), "nothing to draw for {label}");
                    assert!(w > 0.0 && w < 30.0, "{label} is {w} wide");
                    for s in &strokes {
                        assert!(!s.is_empty());
                        for q in s {
                            assert!(q.x > -3.0 && q.x < w + 3.0 && q.y > -1.0 && q.y < 7.0, "{label}: {q:?}");
                        }
                    }
                }
            }
        }
    }
}
