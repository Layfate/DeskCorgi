//! A tiny stroke font for the key pop-ups: capital letters, digits, the punctuation on a
//! keyboard and a few key symbols (shift, enter, arrows…). Every glyph is a set of polylines
//! on a 4 × 6 grid (y down, baseline at 6), drawn with round caps so it matches the soft,
//! outlined art style. No font file is needed.

use crate::geom::{pt, Pt};

/// Width of the glyph grid and the advance from one glyph to the next, in grid units.
pub const GLYPH_W: f32 = 4.0;
pub const GLYPH_H: f32 = 6.0;
pub const ADVANCE: f32 = 5.4;

type Strokes = Vec<Vec<Pt>>;

fn line(pts: &[(f32, f32)]) -> Vec<Pt> {
    pts.iter().map(|&(x, y)| pt(x, y)).collect()
}

/// Points on an ellipse arc from angle `a0` to `a1` (degrees, y down: -90 is the top).
fn arc(cx: f32, cy: f32, rx: f32, ry: f32, a0: f32, a1: f32) -> Vec<Pt> {
    let n = (((a1 - a0).abs() / 15.0).ceil() as usize).max(2);
    (0..=n)
        .map(|i| {
            let a = (a0 + (a1 - a0) * i as f32 / n as f32).to_radians();
            pt(cx + rx * a.cos(), cy + ry * a.sin())
        })
        .collect()
}

fn join(mut a: Vec<Pt>, b: Vec<Pt>) -> Vec<Pt> {
    a.extend(b);
    a
}

